// Modifiers
/*
    public - makes the field or method to be accessible by anyone working with our code.

    private - restricts access to fields or methods so they can only be used within the class.

    static -

    protected - specifies that the member can only be accessed within its own package (as with package-private) and, in addition, by a subclass of its class in another package

    world-level -

    access level - fields(determines who can get or set the value of the field), methods(determines who can call the method)

    access modifier -

    * two levels of access control - 
        top level - public, package-private(no modifier)
        member level - private, protected, 
*/


